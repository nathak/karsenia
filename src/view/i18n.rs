//! The desktop app's words, Korean and English. The language follows the system's (`sys-locale`); Korean when it starts with `ko`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    Ko,
    En,
}

impl Lang {
    pub fn from_system() -> Self {
        match sys_locale::get_locale() {
            Some(l) if l.to_ascii_lowercase().starts_with("ko") => Lang::Ko,
            Some(_) => Lang::En,
            None => Lang::Ko,
        }
    }

    /// The language the person chose in Settings (`ko` or `en`), if they did.
    pub fn from_code(code: &str) -> Option<Self> {
        match code {
            "ko" => Some(Lang::Ko),
            "en" => Some(Lang::En),
            _ => None,
        }
    }

    pub fn code(self) -> &'static str {
        if self == Lang::Ko { "ko" } else { "en" }
    }
}

