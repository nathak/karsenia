// Needs Playwright with Chromium: PLAYWRIGHT=/path/to/node_modules/playwright/index.mjs
const { chromium } = await import(process.env.PLAYWRIGHT || 'playwright')
const SP = process.argv[2], URL = process.argv[3]
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1200, height: 820 } })
const errors = []
page.on('pageerror', e => errors.push('pageerror: ' + e.message))
page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()) })
let alerted = false
page.on('dialog', async d => { if (d.type() === 'alert') alerted = true; await d.dismiss() })
const ok = (cond, what) => { console.log((cond ? 'PASS ' : 'FAIL ') + what); if (!cond) process.exitCode = 1 }

await page.goto(URL)
await page.waitForSelector('#conn:has-text("연결됨")')
ok(!page.url().includes('#t='), 'the token is removed from the address bar')
await page.click('#new-toggle')
await page.fill('#new-cwd', SP + '/project')
await page.click('#new-form button[type=submit]')
await page.waitForSelector('#pill:has-text("대기")')
await page.setInputFiles('#file', SP + '/project/shot.png')
await page.waitForSelector('.chip img')
await page.fill('#input', '이 이미지를 읽고 파일을 만들어줘')
await page.keyboard.press('Enter')
await page.waitForSelector('.msg.user img')
ok(await page.locator('.msg.user img').count() === 1, 'the attached image shows in the user message')
await page.waitForSelector('.msg.asst.live', { timeout: 8000 }).catch(() => {})
await page.screenshot({ path: SP + '/1-streaming.png' })
await page.waitForSelector('#perm[open]', { timeout: 10000 })
await page.screenshot({ path: SP + '/2-permission.png' })
const dlg = await page.locator('#perm').innerText()
ok(dlg.includes('touch done.txt') && dlg.includes('파일 만들기') && dlg.includes('addRules'), 'the permission dialog shows the command, description and suggestions')
ok(await page.locator('#pill:has-text("작업 중")').count() === 1, 'the state is working while it waits')
ok(await page.locator('#perm button').count() === 2, 'the chat-wide allow button is only for the search tool')
await page.click('#perm .primary')
await page.waitForSelector('text=끝났습니다.', { timeout: 10000 })
await page.waitForSelector('#pill:has-text("대기")')
await page.waitForFunction(() => document.querySelector('.tool img.shot')?.naturalWidth > 0, null, { timeout: 8000 }).catch(() => {})
await page.screenshot({ path: SP + '/3-done.png' })
ok(await page.locator('.msg.asst strong').count() >= 1, 'markdown bold is drawn')
ok(await page.locator('.msg.asst pre code').count() === 1, 'a code block is drawn')
ok(await page.locator('.msg.asst img').count() === 0 && !alerted, 'an injected <img onerror> is removed and nothing ran')
ok(await page.locator('.msg.asst a[target=_blank][rel*=noopener]').count() === 1, 'links open in a new tab with noopener')
ok(await page.locator('.tool.done').count() === 1, 'the tool card is marked done')
ok(await page.evaluate(() => document.querySelector('.tool img.shot')?.naturalWidth > 0), 'the project image shows in the tool card (fetched through the checked endpoint)')
ok(await page.locator('.msg.asst.live').count() === 0, 'the live text bubble is replaced by the final one')
ok((await page.locator('#messages').innerText()).includes('$0.0123'), 'cost and time are noted')

// A reload keeps the token for this tab; the session is replayed from the log.
await page.goto(URL.split('#')[0])
await page.waitForSelector('.sess')
await page.click('.sess')
await page.waitForSelector('text=끝났습니다.')
ok(await page.locator('.msg.user img').count() === 1 && await page.locator('.tool').count() === 1, 'reopening replays the user image and the tool card')
ok(await page.locator('#perm[open]').count() === 0, 'no stale permission dialog after the replay')
await page.screenshot({ path: SP + '/4-replay.png' })

// Search: the sidebar finds the words, marks them, and a click scrolls to the message.
await page.fill('#search', '스트리밍')
await page.waitForSelector('#results .res', { timeout: 8000 })
ok(await page.locator('#results mark').first().innerText() === '스트리밍', 'the match is marked in the result')
ok(await page.locator('#sessions').isHidden(), 'results replace the chat list while searching')
await page.click('#results .res')
await page.waitForSelector('.hit', { timeout: 5000 })
ok((await page.locator('.hit').first().innerText()).includes('스트리밍'), 'a click scrolls to the message and marks it')
await page.screenshot({ path: SP + '/5-search.png' })
await page.fill('#search', '굵게')
await page.waitForSelector('#results .res', { timeout: 8000 })
ok(true, 'a two-letter Korean word is found too')
await page.fill('#search', 'zzzqqqnothing')
await page.waitForSelector('#results .muted', { timeout: 8000 })
await page.press('#search', 'Escape')
ok(await page.locator('#sessions').isVisible() && await page.inputValue('#search') === '', 'Escape clears the search and brings the chat list back')
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no console errors')
await browser.close()
